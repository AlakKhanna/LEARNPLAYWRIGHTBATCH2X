// Backticks, single quotes, and double quotes in JavaScript

const name = 'Alak';
const message1 = 'Hello ' + name;          // single quotes
const message2 = "Hello " + name;          // double quotes
const message3 = `Hello ${name}`;          // backticks

console.log(message1);
console.log(message2);
console.log(message3);
