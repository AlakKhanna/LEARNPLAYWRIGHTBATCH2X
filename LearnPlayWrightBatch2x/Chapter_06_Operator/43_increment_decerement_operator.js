//pre increment

let a = 5;
console.log(++a); // Output: 6
console.log(a);   // Output: 6

//post increment

let b = 5;
console.log(b++); // Output: 5
console.log(b);   // Output: 6

//pre decrement

let c = 5;
console.log(--c); // Output: 4
console.log(c);   // Output: 4

//post decrement

let d = 5;
console.log(d--); // Output: 5
console.log(d);   // Output: 4  