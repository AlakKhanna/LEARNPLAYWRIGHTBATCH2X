//modulus operator
var a = 10; // assigns the value 10 to variable a
var b = 3;  // assigns the value 3 to variable b

var remainder = a % b; // modulus operator calculates the remainder of division

// Logging the result of the modulus operation
console.log("Remainder of", a, "divided by", b, "is:", remainder); // Output: Remainder of 10 divided by 3 is: 1